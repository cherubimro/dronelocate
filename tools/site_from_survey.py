#!/usr/bin/env python3
"""Build a site config from surveyed coordinates of the nodes and the radar.

Why this exists. Node positions propagate one-to-one into every fix, so they
come from an RTK survey (ROMPOS in Romania) of each *antenna*, not from a
handheld GPS. The site file, though, wants ENU metres about an origin. This
converts the survey with the same LocalFrame the solver uses, so nobody does
that arithmetic by hand, and prints the geometry it implies.

    python3 tools/site_from_survey.py survey.csv \\
        --template config/site-field.json -o config/site-field.json --in-place
    python3 tools/site_from_survey.py survey.csv --template config/site-field.json \\
        -o /tmp/site-test.json --flight-box -400,400,400,1100,60

survey.csv, one row per antenna (header required, `#` lines ignored):

    id,kind,lat,lon,alt_m
    r01,radar,45.7xxxxxx,21.2xxxxxx,96.40
    n01,node,45.7xxxxxx,21.2xxxxxx,93.10
    ...

alt_m is the antenna's height in ONE reference for every row -- ellipsoidal
(what RTK reports) or above sea level, never mixed; the origin is stored in
the same reference. kind is `node` or `radar`.

The origin is the radar's antenna when there is exactly one radar (the
site's natural centre: plots are measured from it), else --origin ID. Every
other section of the template (radio, solver, hardware, capture, fusion...)
is kept; node entries keep their other fields (gain_db, role, uplink_mbps),
radar entries keep az_offset_deg, beam widths and settings -- the survey
gives positions only, never the mounting azimuth.

Note the frame: with the origin on the radar antenna, every altitude in the
site file -- node enu[2], solver.alt_prior_m, solver.ground_alt_m -- is
metres above that antenna, not above the ground.
"""

import argparse
import csv
import datetime
import itertools
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from dronelocate.geo import LocalFrame, gdop  # noqa: E402


def read_survey(path):
    rows = []
    with open(path, newline="") as f:
        lines = [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]
    for r in csv.DictReader(lines):
        r = {k.strip(): (v or "").strip() for k, v in r.items()}
        kind = r.get("kind", "node").lower()
        if kind not in ("node", "radar"):
            raise SystemExit(f"{r['id']}: kind must be node or radar, not {kind!r}")
        rows.append({"id": r["id"], "kind": kind, "lat": float(r["lat"]),
                     "lon": float(r["lon"]), "alt_m": float(r["alt_m"])})
    ids = [r["id"] for r in rows]
    dup = {i for i in ids if ids.count(i) > 1}
    if dup:
        raise SystemExit(f"duplicate ids in survey: {sorted(dup)}")
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("survey")
    ap.add_argument("--template", required=True, help="site json to take everything else from")
    ap.add_argument("-o", "--output", required=True)
    ap.add_argument("--in-place", action="store_true",
                    help="allow --output to be the template itself")
    ap.add_argument("--origin", help="survey id to use as the ENU origin (default: the radar)")
    ap.add_argument("--alt-ref", default="ellipsoidal", choices=["ellipsoidal", "msl"],
                    help="reference of every alt_m in the survey (recorded in the file)")
    ap.add_argument("--flight-box", metavar="E0,E1,N0,N1,ALT",
                    help="print HDOP/VDOP over this box (ENU metres, altitude above origin)")
    a = ap.parse_args()

    if os.path.abspath(a.output) == os.path.abspath(a.template) and not a.in_place:
        raise SystemExit("output is the template; pass --in-place to overwrite it")

    rows = read_survey(a.survey)
    radars = [r for r in rows if r["kind"] == "radar"]
    nodes = [r for r in rows if r["kind"] == "node"]
    if a.origin:
        org = next((r for r in rows if r["id"] == a.origin), None)
        if org is None:
            raise SystemExit(f"--origin {a.origin} is not in the survey")
    elif len(radars) == 1:
        org = radars[0]
    else:
        raise SystemExit("no single radar to use as origin; pass --origin ID")
    frame = LocalFrame(org["lat"], org["lon"], org["alt_m"])
    enu = {r["id"]: frame.to_enu(r["lat"], r["lon"], r["alt_m"]) for r in rows}

    with open(a.template) as f:
        site = json.load(f)
    today = datetime.date.today().isoformat()

    site["origin"] = {"lat": org["lat"], "lon": org["lon"], "alt_m": org["alt_m"]}
    site["_comment_origin"] = (
        f"Surveyed {today}: origin is {org['id']}'s antenna. Altitudes are "
        f"{a.alt_ref}, the same reference for every entry. Generated by "
        f"tools/site_from_survey.py from {os.path.basename(a.survey)}.")
    site.pop("_comment_geometry", None)

    old_nodes = {n["id"]: n for n in site.get("nodes", [])}
    new_nodes = []
    for r in nodes:
        n = dict(old_nodes.get(r["id"], {"id": r["id"], "role": "hw"}))
        n["enu"] = [round(float(v), 3) for v in enu[r["id"]]]
        new_nodes.append(n)
    site["nodes"] = new_nodes

    old_radars = {r["id"]: r for r in site.get("radars", [])}
    new_radars = []
    for r in radars:
        e = dict(old_radars.get(r["id"], {"id": r["id"], "az_offset_deg": None}))
        e["enu"] = [round(float(v), 3) for v in enu[r["id"]]]
        new_radars.append(e)
    if new_radars or "radars" in site:
        # radars in the template but not in the survey are dropped: an
        # unsurveyed radar position is worse than no radar entry.
        site["radars"] = new_radars

    with open(a.output, "w") as f:
        json.dump(site, f, indent=2)
        f.write("\n")

    # ---- report -----------------------------------------------------------
    print(f"origin {org['id']} ({org['lat']:.7f}, {org['lon']:.7f}, {org['alt_m']:.2f} m {a.alt_ref})")
    print(f"{'id':6} {'kind':6} {'E m':>9} {'N m':>9} {'U m':>8} {'range m':>9}")
    for r in rows:
        e = enu[r["id"]]
        print(f"{r['id']:6} {r['kind']:6} {e[0]:9.2f} {e[1]:9.2f} {e[2]:8.2f} {np.hypot(e[0], e[1]):9.1f}")
    missing = sorted(set(old_nodes) - {r["id"] for r in nodes})
    if missing:
        print(f"note: template nodes not in the survey, dropped: {missing}")
    for r in radars:
        if old_radars.get(r["id"], {}).get("az_offset_deg") is None:
            print(f"note: {r['id']} az_offset_deg is unknown -- the radar stays "
                  "'not calibrated' (not fused) until it is measured")
    if len(nodes) >= 2:
        pts = np.array([enu[r["id"]] for r in nodes])
        dmin = min(np.linalg.norm(p - q) for p, q in itertools.combinations(pts, 2))
        print(f"nodes: {len(nodes)}, closest pair {dmin:.1f} m, height spread "
              f"{pts[:, 2].max() - pts[:, 2].min():.1f} m")
        if len(nodes) < 4:
            print("warning: fewer than 4 nodes -- no 3D TDOA fix is possible")
    if a.flight_box and len(nodes) >= 4:
        e0, e1, n0, n1, alt = (float(v) for v in a.flight_box.split(","))
        pts = np.array([enu[r["id"]] for r in nodes])
        hd, vd = [], []
        for e_ in np.linspace(e0, e1, 9):
            for n_ in np.linspace(n0, n1, 9):
                h, v, _ = gdop(pts, np.array([e_, n_, alt]))
                hd.append(h)
                vd.append(v)
        print(f"flight box E {e0:g}..{e1:g} N {n0:g}..{n1:g} at {alt:g} m: "
              f"HDOP median {np.median(hd):.2f} p90 {np.percentile(hd, 90):.2f}, "
              f"VDOP median {np.median(vd):.2f} p90 {np.percentile(vd, 90):.2f}")
        print("  (multiply by timing sigma in metres -- 1 ns = 0.3 m -- for the expected error;"
              " VDOP > ~100 means the altitude comes from the prior, not the nodes)")
    sv = site.get("solver", {})
    print(f"note: solver.alt_prior_m ({sv.get('alt_prior_m')}) and solver.ground_alt_m "
          f"({sv.get('ground_alt_m')}) are ENU metres ABOVE THE ORIGIN ({org['id']}'s antenna), "
          f"not above the ground -- check them against this frame")
    print(f"wrote {a.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
